CREATE TABLE IF NOT EXISTS sovereignty_events (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 type text NOT NULL CHECK (type IN ('incident','acquisition','policy_change','jurisdiction_change','open_source','closed_source','audit','shutdown','other')),
 impact text NOT NULL CHECK (impact IN ('negative','neutral','positive')),
 severity text NOT NULL DEFAULT 'medium' CHECK (severity IN ('low','medium','high')),
 title text NOT NULL, summary text, source_url text NOT NULL UNIQUE,
 event_date date NOT NULL,
 status text NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','published','rejected')),
 published_at timestamp, proposed_by text, created_at timestamp NOT NULL DEFAULT now()
);
